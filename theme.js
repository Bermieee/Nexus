function validPresetKey(table, value, fallback) {
    const key = String(value || '').trim();
    return Object.prototype.hasOwnProperty.call(table, key) ? key : fallback;
}

function validHex(value, fallback) {
    const raw = String(value || '').trim();
    return /^#[0-9a-f]{6}$/i.test(raw) ? raw.toLowerCase() : fallback;
}

function rgbTuple(hex) {
    const clean = validHex(hex, '#d4af37').slice(1);
    return [0, 2, 4].map(i => parseInt(clean.slice(i, i + 2), 16)).join(',');
}

export function getPresetTheme(name = 'black-gold') {
    const preset = TV2_THEME_PRESETS[name] || TV2_THEME_PRESETS['black-gold'];
    return { preset: Object.keys(TV2_THEME_PRESETS).find(k => TV2_THEME_PRESETS[k] === preset) || 'black-gold', ...preset };
}

export function normalizeTheme(theme = {}) {
    const preset = getPresetTheme(theme.preset || 'black-gold');
    return {
        preset: preset.preset,
        font: validPresetKey(TV2_FONT_PRESETS, theme.font, 'inherit'),
        shape: validPresetKey(TV2_SHAPE_PRESETS, theme.shape, 'soft'),
        background: validHex(theme.background, preset.background),
        surface: validHex(theme.surface, preset.surface),
        surfaceAlt: validHex(theme.surfaceAlt, preset.surfaceAlt),
        accent: validHex(theme.accent, preset.accent),
        accent2: validHex(theme.accent2, preset.accent2),
        text: validHex(theme.text, preset.text),
        muted: validHex(theme.muted, preset.muted),
        border: validHex(theme.border, preset.border),
    };
}

export function applyTv2Theme(theme = {}) {
    const t = normalizeTheme(theme);
    const root = document.documentElement;
    root.style.setProperty('--tv2-bg', t.background);
    root.style.setProperty('--tv2-surface', t.surface);
    root.style.setProperty('--tv2-surface-alt', t.surfaceAlt);
    root.style.setProperty('--tv2-accent', t.accent);
    root.style.setProperty('--tv2-accent-2', t.accent2);
    root.style.setProperty('--tv2-text', t.text);
    root.style.setProperty('--tv2-muted', t.muted);
    root.style.setProperty('--tv2-border', t.border);
    root.style.setProperty('--tv2-accent-rgb', rgbTuple(t.accent));
    root.style.setProperty('--tv2-accent2-rgb', rgbTuple(t.accent2));
    const fontPreset = TV2_FONT_PRESETS[t.font] || TV2_FONT_PRESETS.inherit;
    const shapePreset = TV2_SHAPE_PRESETS[t.shape] || TV2_SHAPE_PRESETS.soft;
    root.style.setProperty('--tv2-font-family', fontPreset.family);
    root.style.setProperty('--tv2-radius-control', shapePreset.control);
    root.style.setProperty('--tv2-radius-card', shapePreset.card);
    root.style.setProperty('--tv2-radius-panel', shapePreset.panel);
    root.dataset.tv2Theme = t.preset;
    root.dataset.tv2Font = t.font;
    root.dataset.tv2Shape = t.shape;
    return t;
}
